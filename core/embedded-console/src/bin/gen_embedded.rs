//! Regenerates the `Cargo.toml` and `src/lib.rs` of every "simple" `embedded-*`
//! crate from [`SIMPLE_EMBEDDED_COMPONENTS`], so adding or changing one of those
//! crates means editing the list in `embedded_components.rs` and re-running this
//! binary, not hand-copying another crate's files.
//!
//! `cargo run -p aws-emulator-embedded-console --bin gen_embedded`

use std::fs;
use std::path::{Path, PathBuf};

include!(concat!(env!("CARGO_MANIFEST_DIR"), "/embedded_components.rs"));

const LICENSE_HEADER: &str = "// SPDX-License-Identifier: CC0-1.0\n\n";

fn main() {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let core_dir = manifest_dir.parent().expect("core/embedded-console has a parent").to_path_buf();

    for (short_name, service_package) in SIMPLE_EMBEDDED_COMPONENTS {
        let crate_dir = core_dir.join(format!("embedded-{short_name}"));
        write_file(&crate_dir.join("Cargo.toml"), &cargo_toml(short_name, service_package));
        write_file(&crate_dir.join("src").join("lib.rs"), &lib_rs(service_package));
        println!("generated {}", crate_dir.display());
    }
}

fn cargo_toml(short_name: &str, service_package: &str) -> String {
    format!(
        r#"[package]
name = "aws-emulator-embedded-{short_name}"
version.workspace = true
edition.workspace = true
license.workspace = true

[lib]
crate-type = ["cdylib", "rlib"]

[dependencies]
http = {{ workspace = true }}
bytes = {{ workspace = true }}
engine = {{ workspace = true }}
smithy-server-runtime = {{ workspace = true }}
emulator-server = {{ workspace = true }}
{service_package} = {{ workspace = true }}
# WASM-EMBEDDED EXPERIMENT: see core/embedded-secretsmanager/Cargo.toml for why these
# two dependencies are split by target.
tokio = {{ version = "1", features = ["sync", "macros", "io-util", "rt", "time"] }}
embedded-console = {{ path = "../embedded-console", package = "aws-emulator-embedded-console" }}

[target.'cfg(not(target_family = "wasm"))'.dependencies]
tokio = {{ version = "1", features = ["rt-multi-thread"] }}

[target.'cfg(target_family = "wasm")'.dependencies]
wstd = {{ workspace = true }}
"#
    )
}

fn lib_rs(service_package: &str) -> String {
    let service_mod = service_package.replace('-', "_");
    format!(
        "{LICENSE_HEADER}\
//! Single-service in-process emulator for `{service_package}`, built for\n\
//! wasm32-wasip2.\n\
//!\n\
//! Registers a single service with no outgoing-handler fallback, so it uses\n\
//! `embedded_console::embedded_service!` -- see that macro's docs for the\n\
//! `build_router`/`wasi:http/proxy` plumbing it generates.\n\
//!\n\
//! Generated by `gen-embedded` from `embedded_components.rs` -- do not hand-edit.\n\
\n\
embedded_console::embedded_service!({service_mod}::EmulatedService);\n"
    )
}

fn write_file(path: &Path, contents: &str) {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).unwrap_or_else(|err| panic!("creating {}: {err}", parent.display()));
    }
    fs::write(path, contents).unwrap_or_else(|err| panic!("writing {}: {err}", path.display()));
}
