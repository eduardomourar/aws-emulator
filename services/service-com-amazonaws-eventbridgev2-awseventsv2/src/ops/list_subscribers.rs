/// The total order `ListSubscribers` enumerates in, and exactly what a `NextToken`
/// carries: the name the list is ordered by, with the ARN breaking ties.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
struct PageKey {
    name: String,
    arn: String,
}

/// This operation's page cursor as the opaque `NextToken` the next request replays,
/// rendered by the one page-token codec this service's List operations share
/// ([`crate::state::encode_page_token`]).
fn encode_next_token(key: &PageKey) -> String {
    crate::state::encode_page_token(&[&key.name, &key.arn])
}

/// Read a cursor back out of a `NextToken`. `None` when the token is not one this
/// service issued for this enumeration's cursor.
fn decode_next_token(token: &str) -> Option<PageKey> {
    let mut fields = crate::state::decode_page_token(token, 2)?.into_iter();
    Some(PageKey {
        name: fields.next()?,
        arn: fields.next()?,
    })
}

#[cfg(test)]
mod tests {
    use super::{decode_next_token, encode_next_token, PageKey};

    /// A cursor survives the token it is rendered as, and nothing else is read as a
    /// cursor: the token is this operation's own encoding, so its round-trip is
    /// pinned here beside it.
    #[test]
    fn a_cursor_round_trips_through_its_token() {
        let key = PageKey {
            name: "demo-subscriber".to_string(),
            arn: "arn:aws:events:us-east-1:000000000000:subscriber/demo-subscriber/abc"
                .to_string(),
        };
        let token = encode_next_token(&key);
        assert_eq!(decode_next_token(&token).as_ref(), Some(&key));

        for token in ["not-a-token", "abc", "6162"] {
            assert!(decode_next_token(token).is_none());
        }
    }
}
